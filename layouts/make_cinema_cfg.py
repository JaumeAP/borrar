# Cinema room 11 m (screen to back) x 6.5 m x 3.80 m -> IABLib renderer configuration.
# Coordinates: x from the left wall, y from the screen, z from the floor (m). Each speaker goes to the IAB unit cube
# (x / width, y / length; z 0 for the screen and wall layer, 1 for the ceiling) and its angles are those IABLib gives
# that cube position (IABTransform::TransformIABToSphericalVBAP, through the cubeangles tool, argv[2]), so an object
# at a speaker's place in the room plays on that speaker.
#
# Usage: python3 -I layouts/make_cinema_cfg.py <output .cfg> <cubeangles executable>
# Design and verification in layouts/docs/design.md.
import itertools, math, subprocess, sys
W, LEN = 6.5, 11.0
LAYER, CEIL = 2.40, 3.80
URI = {
 'L': 'urn:smpte:ul:060E2B34.0401010D.03020101.00000000', 'C': 'urn:smpte:ul:060E2B34.0401010D.03020103.00000000',
 'R': 'urn:smpte:ul:060E2B34.0401010D.03020102.00000000', 'LFE': 'urn:smpte:ul:060E2B34.0401010D.03020104.00000000',
 'Lss': 'urn:smpte:ul:060E2B34.0401010D.03020107.00000000', 'Rss': 'urn:smpte:ul:060E2B34.0401010D.03020108.00000000',
 'Lrs': 'urn:smpte:ul:060E2B34.0401010D.03020109.00000000', 'Rrs': 'urn:smpte:ul:060E2B34.0401010D.0302010A.00000000',
 'Ls': 'urn:smpte:ul:060E2B34.0401010D.03020105.00000000', 'Rs': 'urn:smpte:ul:060E2B34.0401010D.03020106.00000000',
 'Lts': 'http://dts.com/mda/channels#TSL', 'Rts': 'http://dts.com/mda/channels#TSR'}

def cube(x, y, z):
    return x / W, y / LEN, (0.0 if z <= LAYER else 1.0)

ys = [2.0 + 1.5 * i for i in range(7)]         # 7 per wall and per ceiling line, 2 m to 11 m
spk = []                                         # (name, x, y, z, uri)
spk += [('L', 1.0, 0, 2.0, URI['L']), ('C', W / 2, 0, 2.0, URI['C']), ('R', W - 1.0, 0, 2.0, URI['R'])]
spk += [('LFE', W / 2, 0, 0, URI['LFE'])]
spk += [('LSS%d' % (i + 1), 0.0, y, LAYER, None) for i, y in enumerate(ys)]
spk += [('RSS%d' % (i + 1), W, y, LAYER, None) for i, y in enumerate(ys)]
spk += [('LTS%d' % (i + 1), W / 3, y, CEIL, None) for i, y in enumerate(ys)]
spk += [('RTS%d' % (i + 1), 2 * W / 3, y, CEIL, None) for i, y in enumerate(ys)]
rear = [W / 8 * (2 * i + 1) for i in range(4)]  # 4 equal parts of the back wall
spk += [('LRS1', rear[0], LEN, LAYER, None), ('LRS2', rear[1], LEN, LAYER, None),
        ('RRS2', rear[2], LEN, LAYER, None), ('RRS1', rear[3], LEN, LAYER, None)]

# Bed channels as arrays: virtual speakers with the channel's URI, mapped to their zone (IABLib normalises to unit power)
side = lambda s: ['%sSS%d' % (s, i + 1) for i in range(7)]
top = lambda s: ['%sTS%d' % (s, i + 1) for i in range(7)]
back = lambda s: ['%sRS1' % s, '%sRS2' % s]
virtual = [('VLSS', -90, 'Lss', side('L')), ('VRSS', 90, 'Rss', side('R')),
           ('VLRS', -150, 'Lrs', back('L')), ('VRRS', 150, 'Rrs', back('R')),
           ('VLS', -110, 'Ls', side('L') + back('L')), ('VRS', 110, 'Rs', side('R') + back('R'))]
virtual_top = [('VLTS', -90, 'Lts', top('L')), ('VRTS', 90, 'Rts', top('R'))]

out = []
out.append('# Cinema room, 11 m (screen to back wall) x 6.5 m, ceiling 3.80 m.')
out.append('# Screen: L C R at 2.00 m, L and R 1 m from the side walls; LFE.')
out.append('# Side walls: 7 surrounds each at 2.40 m, from 2 m to 11 m from the screen, every 1.5 m.')
out.append('# Ceiling: two lines of 7 at 3.80 m, at 1/3 and 2/3 of the width, from 2 m to 11 m.')
out.append('# Back wall: 4 at 2.40 m, centred in 4 equal parts of the width.')
out.append('# Angles: those IABLib gives each speaker\'s place in the IAB unit cube (x / 6.5, y / 11; z 0 for the screen')
out.append('# and wall layer, 1 for the ceiling), so an object at a speaker\'s place plays on that speaker.')
out.append('# Bed channels Lss Rss Lrs Rrs Ls Rs Lts Rts play on their whole zone (virtual speakers with maps, unit power).')
out.append('# Generated by layouts/make_cinema_cfg.py.')
out.append('v 3')
out.append('c   smooth   1')
out.append('e   urn:smpte:ul:060E2B34.0401010D.03020202.00000000')
out.append('# s   name   chan   theta   phi   exception-uri')
query = ''.join('%s %.6f %.6f %.6f\n' % ((n,) + cube(x, y, z)) for n, x, y, z, _ in spk if n != 'LFE')
reply = subprocess.run([sys.argv[2]], input=query, capture_output=True, text=True, check=True).stdout.split('\n')
ang = {}
for line in reply:
    if line:
        n, a, e = line.split()
        ang[n] = (round(math.degrees(float(a)), 2), round(math.degrees(float(e)), 2))
dirs = {}
for ch, (n, x, y, z, uri) in enumerate(spk):
    t, p = (0.0, 0.0) if n == 'LFE' else ang[n]
    if n != 'LFE':
        dirs[n] = (t, p)
    out.append('s   %-6s %3d  %8.2f  %6.2f%s' % (n, ch, t, p, ('   ' + uri) if uri else ''))
avg_phi = sum(dirs['LTS%d' % (i + 1)][1] for i in range(7)) / 7
for n, t, bed, _ in virtual:
    out.append('s   %-6s   *  %8.2f  %6.2f   %s' % (n, t, 0.0, URI[bed]))
for n, t, bed, _ in virtual_top:
    out.append('s   %-6s   *  %8.2f  %6.2f   %s' % (n, t, avg_phi, URI[bed]))
out.append('w   LFE')
out.append('# m   name   (speaker-name   downmix-coefficient)+')
for n, _, _, targets in virtual + virtual_top:
    out.append('m   %s   %s' % (n, '   '.join('%s 1.0' % s for s in targets)))

# VBAP patches: the convex hull of the physical directions, minus the floor face (the elevation-0 ring).
def vec(t, p):
    t, p = math.radians(t), math.radians(p)
    return (math.cos(p) * math.sin(t), math.cos(p) * math.cos(t), math.sin(p))
names = list(dirs)
V = {n: vec(*dirs[n]) for n in names}
def sub(a, b): return tuple(a[i] - b[i] for i in range(3))
def cross(a, b): return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])
def dot(a, b): return sum(a[i] * b[i] for i in range(3))
eps = 1e-9
tris = []
for a, b, c in itertools.combinations(names, 3):
    nrm = cross(sub(V[b], V[a]), sub(V[c], V[a]))
    if dot(nrm, nrm) < 1e-12:
        continue
    side_ = [dot(nrm, sub(V[q], V[a])) for q in names if q not in (a, b, c)]
    if all(s <= eps for s in side_) or all(s >= -eps for s in side_):
        if all(abs(dirs[q][1]) < 1e-9 for q in (a, b, c)):
            continue                          # the floor face
        tris.append((a, b, c))
out.append('# p   speaker1-name   speaker2-name   speaker3-name')
out.append('# Triangle patches (convex hull, overlapping where four speakers are coplanar): %d' % len(tris))
for t in tris:
    out.append('p   %s   %s   %s' % t)
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print(len(spk), 'outputs,', len(tris), 'patches')
